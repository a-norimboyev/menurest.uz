let currentAdminLang = localStorage.getItem('admin_lang') || 'uz';

function at(key) {
  if (adminTranslations[currentAdminLang] && adminTranslations[currentAdminLang][key]) {
    return adminTranslations[currentAdminLang][key];
  }
  return adminTranslations.uz[key] || key;
}

function setAdminLanguage(lang) {
  if (adminTranslations[lang]) {
    currentAdminLang = lang;
    localStorage.setItem('admin_lang', lang);
    if (typeof applyAdminLanguage === 'function') {
      applyAdminLanguage();
    }
    if (typeof renderOrders === 'function') renderOrders();
    if (typeof renderCategoriesTable === 'function' && typeof currentCategories !== 'undefined') renderCategoriesTable();
    if (typeof renderQRCodes === 'function' && typeof allQrCodes !== 'undefined' && allQrCodes.length) renderQRCodes();
    if (typeof renderStaffTable === 'function' && typeof currentStaffList !== 'undefined') renderStaffTable();
    if (typeof loadBossData === 'function' && typeof currentRole !== 'undefined' && currentRole === 'boss') loadBossData();
    if (typeof loadCashierData === 'function' && typeof currentRole !== 'undefined' && currentRole === 'cashier') loadCashierData();
    if (typeof loadWaiterData === 'function' && typeof currentRole !== 'undefined' && currentRole === 'waiter') loadWaiterData();
  }
}
window.setAdminLanguage = setAdminLanguage;
window.at = at;
